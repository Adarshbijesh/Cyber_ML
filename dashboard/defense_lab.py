"""
defense_lab.py — Dashboard Page 4: Defense Laboratory
"""

import os
import sys
import json
import numpy as np
import pandas as pd
import streamlit as st
import plotly.graph_objects as go
import joblib

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from config import (
    BASELINE_DIR, DEFENDED_DIR, RESULTS_DIR, TEST_PATH, SCALER_PATH,
    PGD_EPSILON, N_FEATURES,
)
from src.train import load_model, list_available_models
from src.data_loader import split_features_labels


DEFENSE_INFO = {
    "Adversarial Training": {
        "icon": "🏋️",
        "color": "#00D4FF",
        "description": "Augments the training set with adversarial examples generated by PGD attack on a preliminary model. "
                       "The final model learns to correctly classify both clean and adversarially perturbed samples.",
        "file": "adversarial_training_rf.joblib",
        "trade_off": "Slight reduction in clean accuracy. Significant improvement in adversarial robustness.",
    },
    "Input Validation": {
        "icon": "🔒",
        "color": "#00E676",
        "description": "Sanitizes input features by clipping values to observed training distribution bounds (mean ± 3σ). "
                       "Extreme out-of-distribution perturbations are suppressed before prediction.",
        "file": "input_validation.joblib",
        "trade_off": "Minimal clean accuracy impact. Effective against large-magnitude perturbations.",
    },
    "Ensemble Defense": {
        "icon": "🏛️",
        "color": "#7B2FBE",
        "description": "Soft-voting ensemble of Random Forest, Gradient Boosting, and Logistic Regression. "
                       "Adversarial examples must fool all models simultaneously, reducing attack success rates.",
        "file": "ensemble_defense.joblib",
        "trade_off": "Increased computation. Diverse classifiers are harder to attack simultaneously.",
    },
}


def render():
    st.markdown("""
    <div style="background:#0F1F3D; border-left:4px solid #7B2FBE;
                border-radius:8px; padding:16px 20px; margin-bottom:20px;">
        <h2 style="color:#7B2FBE; margin:0; font-size:1.5rem;">🛡️ Defense Laboratory</h2>
        <p style="color:#8899BB; margin:6px 0 0 0; font-size:0.9rem;">
            Compare baseline and defended models. Analyze clean accuracy vs robustness trade-offs.
        </p>
    </div>
    """, unsafe_allow_html=True)

    # Check if defended models exist
    defended_models_exist = os.path.exists(DEFENDED_DIR) and any(
        f.endswith(".joblib") for f in os.listdir(DEFENDED_DIR)
    ) if os.path.exists(DEFENDED_DIR) else False

    if not defended_models_exist:
        st.warning("""
        Defense models not yet trained. Run the full experiment pipeline:
        ```
        python experiments/run_experiments.py
        ```
        """)

    # ── Defense Cards ──────────────────────────────────────────────────────────
    st.markdown("#### 🔬 Defense Mechanisms")
    cols = st.columns(3)
    for col, (name, info) in zip(cols, DEFENSE_INFO.items()):
        file_path = os.path.join(DEFENDED_DIR, info["file"]) if DEFENDED_DIR else ""
        exists = os.path.exists(file_path)
        with col:
            st.markdown(f"""
            <div style="background:#0F1F3D; border: 1px solid {info['color']}44;
                        border-top: 3px solid {info['color']}; border-radius:10px; padding:16px;">
                <div style="display:flex; align-items:center; gap:8px; margin-bottom:8px;">
                    <span style="font-size:1.3rem;">{info['icon']}</span>
                    <strong style="color:{info['color']};">{name}</strong>
                    <span style="margin-left:auto; font-size:0.75rem;
                                 color:{'#00E676' if exists else '#FF6B35'};">
                        {'✅ Trained' if exists else '⏳ Pending'}
                    </span>
                </div>
                <p style="color:#8899BB; font-size:0.82rem; margin:0 0 8px 0;">{info['description']}</p>
                <div style="background:#162040; border-radius:4px; padding:6px 10px;
                            font-size:0.78rem; color:{info['color']};">
                    Trade-off: {info['trade_off']}
                </div>
            </div>
            """, unsafe_allow_html=True)

    # ── Load Data ──────────────────────────────────────────────────────────────
    st.markdown("---")

    test_df = None
    if os.path.exists(TEST_PATH):
        test_df = pd.read_csv(TEST_PATH)

    baseline_rf = None
    baseline_models = list_available_models()
    if "random_forest" in baseline_models:
        baseline_rf = load_model("random_forest")

    # ── Performance Comparison Table ───────────────────────────────────────────
    st.markdown("#### 📊 Model Performance Comparison")

    defense_metrics_path = os.path.join(RESULTS_DIR, "defense_metrics.json")
    baseline_metrics_path = os.path.join(RESULTS_DIR, "baseline_metrics.json")

    comparison_rows = []

    if os.path.exists(baseline_metrics_path):
        with open(baseline_metrics_path) as f:
            bl = json.load(f)
        for name in ["random_forest", "gradient_boosting", "logistic_regression"]:
            if name in bl:
                m = bl[name].get("test", {})
                comparison_rows.append({
                    "Model": name.replace("_", " ").title(),
                    "Type": "Baseline",
                    "Accuracy": m.get("accuracy", 0),
                    "Precision": m.get("precision", 0),
                    "Recall": m.get("recall", 0),
                    "F1-Score": m.get("f1", 0),
                    "ROC-AUC": m.get("roc_auc") or 0,
                })

    # Compute defense metrics live if test data available
    if test_df is not None and defended_models_exist:
        X_test, y_test, _ = split_features_labels(test_df)
        from sklearn.metrics import accuracy_score, f1_score, roc_auc_score, precision_score, recall_score

        for defense_name, info in DEFENSE_INFO.items():
            file_path = os.path.join(DEFENDED_DIR, info["file"])
            if os.path.exists(file_path):
                try:
                    model = joblib.load(file_path)
                    preds = model.predict(X_test)
                    acc = accuracy_score(y_test, preds)
                    f1 = f1_score(y_test, preds, zero_division=0)
                    prec = precision_score(y_test, preds, zero_division=0)
                    rec = recall_score(y_test, preds, zero_division=0)
                    if hasattr(model, "predict_proba"):
                        probs = model.predict_proba(X_test)[:, 1]
                        auc = roc_auc_score(y_test, probs)
                    else:
                        auc = 0
                    comparison_rows.append({
                        "Model": defense_name,
                        "Type": "Defended",
                        "Accuracy": acc,
                        "Precision": prec,
                        "Recall": rec,
                        "F1-Score": f1,
                        "ROC-AUC": auc,
                    })
                except Exception as e:
                    pass

    if comparison_rows:
        df_comp = pd.DataFrame(comparison_rows)
        # Style the dataframe
        for col in ["Accuracy", "Precision", "Recall", "F1-Score", "ROC-AUC"]:
            if col in df_comp.columns:
                df_comp[col] = df_comp[col].map(lambda x: f"{x:.4f}")

        def highlight_defended(row):
            if row.get("Type") == "Defended":
                return ["background-color: rgba(0,212,255,0.08)"] * len(row)
            return [""] * len(row)

        st.dataframe(
            df_comp,
            use_container_width=True,
            hide_index=True,
        )

        # Accuracy comparison chart
        if len(comparison_rows) > 0:
            models_list = [r["Model"] for r in comparison_rows]
            accs = [float(r["Accuracy"]) if isinstance(r["Accuracy"], str) else r["Accuracy"]
                    for r in comparison_rows]
            types = [r["Type"] for r in comparison_rows]
            type_colors = ["#8899BB" if t == "Baseline" else "#00D4FF" for t in types]

            fig_bar = go.Figure(go.Bar(
                x=models_list, y=[a * 100 for a in accs],
                marker_color=type_colors,
                text=[f"{a*100:.2f}%" for a in accs],
                textposition="outside",
            ))
            fig_bar.update_layout(
                title="Clean Accuracy: Baseline vs Defended",
                yaxis=dict(range=[0, 115], title="Accuracy (%)"),
                paper_bgcolor="#0A1628", plot_bgcolor="#0F1F3D",
                font=dict(color="#E8EAF6"),
                margin=dict(l=20, r=20, t=50, b=80),
                height=360,
                xaxis=dict(tickangle=-15),
            )
            # Add legend annotation
            fig_bar.add_annotation(
                x=0, y=108, text="Gray = Baseline, Cyan = Defended",
                showarrow=False, font=dict(color="#8899BB", size=10),
                xanchor="left",
            )
            st.plotly_chart(fig_bar, use_container_width=True)

    # ── Adversarial Robustness Comparison ──────────────────────────────────────
    st.markdown("---")
    st.markdown("#### ⚔️ Adversarial Robustness Analysis")

    attack_results_path = os.path.join(RESULTS_DIR, "attack_results.json")
    if os.path.exists(attack_results_path) and os.path.exists(TEST_PATH):
        try:
            with open(attack_results_path) as f:
                atk = json.load(f)

            # Show attack success rates for available models
            attack_methods = ["FGSM", "PGD", "GeneticAlgorithm", "Random"]
            model_names = list(atk.keys())

            if model_names:
                fig_rob = go.Figure()
                colors = ["#8899BB", "#FF6B35", "#FF1744", "#7B2FBE"]

                for i, m_name in enumerate(model_names[:3]):
                    asr_values = []
                    for method in attack_methods:
                        asr = atk.get(m_name, {}).get(method, {}).get("attack_success_rate", 0) or 0
                        asr_values.append(asr * 100)
                    fig_rob.add_trace(go.Bar(
                        name=m_name,
                        x=attack_methods,
                        y=asr_values,
                        text=[f"{v:.1f}%" for v in asr_values],
                        textposition="outside",
                    ))

                fig_rob.update_layout(
                    title="Attack Success Rate by Method and Model",
                    barmode="group",
                    yaxis=dict(range=[0, 115], title="Attack Success Rate (%)"),
                    paper_bgcolor="#0A1628", plot_bgcolor="#0F1F3D",
                    font=dict(color="#E8EAF6"),
                    height=360,
                    margin=dict(l=20, r=20, t=50, b=20),
                )
                st.plotly_chart(fig_rob, use_container_width=True)
        except Exception as e:
            st.info("Attack results not yet computed. Run `python experiments/run_experiments.py`")
    else:
        st.info("Run `python experiments/run_experiments.py` to generate robustness analysis data.")

    # ── Clean vs Robust Accuracy Trade-off ────────────────────────────────────
    st.markdown("---")
    st.markdown("#### 📉 Clean Accuracy vs Adversarial Robustness Trade-off")
    st.markdown("""
    <div style="background:#0F1F3D; border-radius:8px; padding:14px 18px; color:#8899BB; font-size:0.88rem;">
        <strong style="color:#E8EAF6;">Key Insight:</strong> There is an inherent tension between
        clean accuracy and adversarial robustness. Adversarial training typically reduces clean accuracy
        by 1–5% while improving resistance to attacks. This is a known phenomenon in ML security research.
        <br><br>
        <strong style="color:#00D4FF;">Our experiment design:</strong> Uses identical test sets and attack budgets
        for fair comparison. All reported metrics are on held-out test data not seen during training.
    </div>
    """, unsafe_allow_html=True)

    # Conceptual trade-off visualization
    fig_tradeoff = go.Figure()
    # Scatter points for different models
    models_scatter = [
        ("Random Forest (Baseline)", 0.99, 0.75, "#8899BB"),
        ("Gradient Boosting", 0.98, 0.72, "#7CB9E8"),
        ("Logistic Regression", 0.95, 0.80, "#7B2FBE"),
        ("Adversarial Training RF", 0.97, 0.88, "#00D4FF"),
        ("Ensemble Defense", 0.98, 0.85, "#00E676"),
        ("Input Validation", 0.99, 0.82, "#FFD600"),
    ]
    for name, clean, robust, color in models_scatter:
        fig_tradeoff.add_trace(go.Scatter(
            x=[clean * 100], y=[robust * 100],
            mode="markers+text",
            name=name,
            marker=dict(size=16, color=color, opacity=0.9,
                        line=dict(color="white", width=1)),
            text=[name.split("(")[0].strip()],
            textposition="top center",
            textfont=dict(size=9),
        ))
    fig_tradeoff.update_layout(
        title="Conceptual: Clean Accuracy vs Robust Accuracy",
        xaxis=dict(title="Clean Test Accuracy (%)", range=[90, 102]),
        yaxis=dict(title="Estimated Robust Accuracy (%)", range=[60, 100]),
        paper_bgcolor="#0A1628", plot_bgcolor="#0F1F3D",
        font=dict(color="#E8EAF6"),
        height=380,
        margin=dict(l=40, r=20, t=50, b=40),
        showlegend=False,
    )
    fig_tradeoff.add_annotation(
        x=96, y=65, text="[Conceptual illustration — not from experiment measurements]",
        showarrow=False, font=dict(color="#FFD600", size=9), bgcolor="rgba(0,0,0,0.5)",
    )
    st.plotly_chart(fig_tradeoff, use_container_width=True)
